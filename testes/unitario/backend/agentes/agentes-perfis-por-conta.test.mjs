import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { criarPrimeiraConta } from '../../../apoio/contas-por-email.mjs';
import { criarContaPelaAdministracao, salvarAgentesDaPlataforma, agentesDaPlataformaParaJanela } from '../../../../dist/administracao/servico.js';
import { entrarNaConta, sairDaConta, trocarMinhaSenha } from '../../../../dist/login/regras/contas.js';
import { encerrarSessao, contaDaSessao } from '../../../../dist/login/regras/sessao.js';
import { conferirAcessoAoCanal } from '../../../../dist/login/regras/conferirAcessoAoCanal.js';
import { salvarPreferenciasDoAgente, lerPreferenciasDosAgentes, salvarAgentePessoal, listarAgentesPessoais } from '../../../../dist/agentes/regras/agentesPessoais.js';
import { agentesDoChat } from '../../../../dist/agentes/chat/roteamento.js';
import { especializacoes, personalidades } from '../../../../dist/agentes/tipos/persona.js';
const projeto='11111111-1111-4111-8111-111111111111';
test('Admin define UI/UX oficial e duas contas mantêm personalizações e agentes privados separados', async t => {
  const b=fs.mkdtempSync(path.join(os.tmpdir(),'prumo-uiux-contas-'));
  t.after(()=>{encerrarSessao();fs.rmSync(b,{recursive:true,force:true});});
  const admin=(await criarPrimeiraConta({email:'admin-ux@prumo.test',nome:'Admin UX',senha:'Nuvem-Verde-2026!'},b)).conta;
  assert.equal(admin.admin,true);
  assert.doesNotThrow(()=>conferirAcessoAoCanal('plataforma:salvar',b));
  assert.ok(especializacoes.some(x=>x.id==='ui-ux'));
  assert.ok(personalidades['ui-ux']?.foco);
  const oficial={nome:'UX do Prumo',profissao:'Designer de Produto',especialidade:'Experiência e interface',tom:'Enxuto e técnico'};
  salvarAgentesDaPlataforma({desligados:[],iaExterna:true,orquestracao:true,perfis:{'ui-ux':oficial}},b);
  assert.equal(agentesDaPlataformaParaJanela(b).agentes.find(x=>x.id==='ui-ux')?.nome,'UX do Prumo');
  const comum=await criarContaPelaAdministracao({login:'maria.qa',nome:'Maria QA',papel:'qa'},b);
  sairDaConta(b);
  await entrarNaConta({login:'maria.qa',senha:comum.senhaTemporaria},b);
  await trocarMinhaSenha({atual:comum.senhaTemporaria,nova:'Trilho-Azul-27-2026!'},b);
  assert.equal(contaDaSessao(b)?.id,comum.conta.id);
  assert.throws(()=>conferirAcessoAoCanal('plataforma:salvar',b),/PERMISSION_DENIED/);
  assert.doesNotThrow(()=>conferirAcessoAoCanal('agentes:preferenciassalvar',b));
  assert.equal(agentesDoChat(null,b).find(x=>x.id==='ui-ux')?.nome,'UX do Prumo');
  salvarPreferenciasDoAgente('ui-ux',{apelido:'UX da Maria',orientacao:'Priorize tarefas de acessibilidade'},comum.conta.id,b);
  assert.equal(agentesDoChat(null,b).find(x=>x.id==='ui-ux')?.nome,'UX da Maria');
  assert.deepEqual(lerPreferenciasDosAgentes(admin.id,b),{});
  const pessoal=salvarAgentePessoal(projeto,{nome:'Agenda da Maria',descricao:'Consulta horários',objetivo:'Orientar agenda',instrucoes:'Nunca criar compromisso sem confirmação',publico:false},comum.conta.id,b);
  assert.equal(listarAgentesPessoais(projeto,comum.conta.id,b)[0].nome,'Agenda da Maria');
  assert.deepEqual(listarAgentesPessoais(projeto,admin.id,b),[]);
  sairDaConta(b);
  await entrarNaConta({login:'admin-ux',senha:'Nuvem-Verde-2026!'},b);
  assert.equal(contaDaSessao(b)?.id,admin.id);
  assert.equal(agentesDoChat(null,b).find(x=>x.id==='ui-ux')?.nome,'UX do Prumo');
  assert.deepEqual(lerPreferenciasDosAgentes(admin.id,b),{});
  assert.doesNotThrow(()=>conferirAcessoAoCanal('plataforma:salvar',b));
  assert.throws(()=>salvarPreferenciasDoAgente('orquestrador',{apelido:'Não pode',orientacao:''},admin.id,b),/AGENT_NOT_FOUND/);
  assert.equal(agentesDaPlataformaParaJanela(b).agentes.find(x=>x.id==='ui-ux')?.nome,'UX do Prumo');
});
